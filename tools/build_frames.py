"""Deprecated: 胡胡's frames2d stage.

Kept because the design doc's rebuild sequence still names it. The frames are
generated by ``pets/huhu-carrot.json`` and ``tools/petkit``; the whole pipeline
including manifests and previews is ``python tools/build_pet.py``. Running one
stage is still possible: ``python tools/build_pet.py huhu-carrot --stage frames2d``.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from petkit.build import build  # noqa: E402

SPEC = 'huhu-carrot'


def main():
    spec, results = build(SPEC, stages=['frames2d'])
    frames = results['frames2d']['frames']
    for track, count in frames.items():
        print(track, count)
    print('wrote', results['frames2d']['record'])


if __name__ == '__main__':
    main()
